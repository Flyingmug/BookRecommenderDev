package bookrecommenderdev.client.routing.animation;

/**
 * Enumerazione che rappresenta la direzione logica di una transizione.
 *
 * <p>La direzione viene utilizzata dalle animazioni
 * per determinare il verso di spostamento degli elementi
 * durante una transizione.</p>
 */
public enum Direction {
  TOP,
  BOTTOM,
  RIGHT,
  LEFT
}
